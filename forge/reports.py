"""Research report rendering and citation checks.

Citation integrity is checked mechanically: every evidence item must name a
source; sources that are repository paths must exist in the task's checkout.
Unresolved citations are reported prominently (never silently dropped) and are
passed to later phases through the report artifacts.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

EVIDENCE_KEYS = ("claims", "evidence")


def _evidence_items(data: dict) -> list[dict]:
    items: list[dict] = []
    for k in EVIDENCE_KEYS:
        items += [e for e in data.get(k) or [] if isinstance(e, dict)]
    for c in data.get("candidates") or []:
        items += [e for e in c.get("evidence") or [] if isinstance(e, dict)]
    return items


def citation_check(data: dict, root: Path) -> dict[str, Any]:
    items = _evidence_items(data)
    unresolved, missing_source, resolved = [], [], 0
    for e in items:
        src = (e.get("source") or "").strip()
        if not src or src.lower() in ("none", "n/a", "unknown"):
            if e.get("evidence_type") in ("verified_in_source", "source_reported"):
                missing_source.append(e.get("claim", "")[:200])
            continue
        path = src.split("#")[0].split(":")[0].strip().lstrip("./")
        if "/" in path or path.endswith((".md", ".json", ".py", ".csv", ".bib", ".txt", ".toml")):
            if (root / path).exists():
                resolved += 1
            else:
                unresolved.append(src)
        else:
            resolved += 1  # non-path source (e.g. a paper id already cited in the repository)
    by_type: dict[str, int] = {}
    for e in items:
        by_type[e.get("evidence_type", "unknown")] = by_type.get(e.get("evidence_type", "unknown"), 0) + 1
    return {"evidence_items": len(items), "resolved": resolved, "unresolved": sorted(set(unresolved)),
            "verified_type_without_source": missing_source, "by_evidence_type": by_type}


def _ev(e: dict) -> str:
    loc = f", {e['locator']}" if e.get("locator") else ""
    return f"- {e.get('claim', '')} — *{e.get('evidence_type', 'unknown')}* ({e.get('source', 'no source')}{loc})"


def render_report(phase: str, agent: str, task: dict, data: dict, check: dict) -> str:
    out = [f"# {phase.replace('_', ' ').title()} — {agent}", "",
           f"Forge task `{task['id']}` · workflow `{task['workflow']}` · generated by Forge from the agent's "
           "structured output. Claims are labelled by evidence type; *interpretation* and *unknown* are not "
           "verified findings.", ""]
    if data.get("decision"):
        out += [f"## Decision: **{data['decision']}** (confidence {data.get('confidence', '?')})", "",
                data.get("justification", ""), ""]
    if data.get("summary"):
        out += ["## Summary", "", data["summary"], ""]
    if data.get("claims"):
        out += ["## Claims and evidence", ""] + [_ev(e) for e in data["claims"]] + [""]
    for c in data.get("candidates") or []:
        out += [f"## Candidate: {c.get('contribution', '')}", "", f"Assessment: **{c.get('assessment')}**",
                f"Closest prior art: {', '.join(c.get('closest_prior_art') or []) or 'none identified'}",
                f"Overlap: {c.get('overlap', '')}", ""] + [_ev(e) for e in c.get("evidence") or []] + [""]
    if data.get("agreements"):
        out += ["## Agreements", ""] + [f"- {a}" for a in data["agreements"]] + [""]
    if data.get("disagreements"):
        out += ["## Disagreements checked against primary sources", ""]
        for d in data["disagreements"]:
            out += [f"### {d.get('topic', '')}", f"- This analysis: {d.get('this_position', '')}",
                    f"- Other analysis: {d.get('other_position', '')}",
                    f"- Primary source check: {d.get('primary_source_check', '')}",
                    f"- Resolution: **{d.get('resolution', '')}**", ""]
    if data.get("unsupported_claims_found"):
        out += ["## Claims not supported by their cited sources", ""] + \
               [f"- {x}" for x in data["unsupported_claims_found"]] + [""]
    if data.get("evidence"):
        out += ["## Evidence", ""] + [_ev(e) for e in data["evidence"]] + [""]
    for key, title in (("disagreements_resolved", "Disagreements resolved"), ("open_questions", "Open questions"),
                       ("limitations", "Limitations"), ("next_steps", "Next steps")):
        if data.get(key):
            out += [f"## {title}", ""] + [f"- {x}" for x in data[key]] + [""]
    out += ["## Citation check (by Forge)", "",
            f"{check['evidence_items']} evidence item(s); {check['resolved']} resolved; "
            f"{len(check['unresolved'])} cited path(s) not found in the repository.", ""]
    out += [f"- NOT FOUND: `{u}`" for u in check["unresolved"]]
    out += [f"- Claimed as sourced but no source given: {m}" for m in check["verified_type_without_source"]]
    return "\n".join(out).rstrip() + "\n"
